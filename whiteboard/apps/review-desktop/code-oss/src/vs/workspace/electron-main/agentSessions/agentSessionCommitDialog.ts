/** Formats untrusted proposal text so controls and bidirectional marks remain visible in dialogs. */
export function formatCommitDialogValue(value: string): string {
	return JSON.stringify(value).replace(/[\u007f-\u009f\u061c\u200e\u200f\u2028\u2029\u202a-\u202e\u2066-\u2069]/g, character => `\\u${character.charCodeAt(0).toString(16).padStart(4, '0')}`);
}
